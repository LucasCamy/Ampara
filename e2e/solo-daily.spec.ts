import { at, expect, goSettings, goTab, noHorizontalOverflow, PASSWORDS, quick, skipTour, test, type Page } from './fixtures'

export async function createSolo(page: Page) {
  await at(page, '10:00')
  await skipTour(page)
  await page.goto('/')
  await page.getByTestId('setup-mode-solo').click()
  await page.getByTestId('setup-name').fill('Lucas')
  await page.getByTestId('setup-password').fill(PASSWORDS.A)
  await page.getByTestId('setup-password2').fill(PASSWORDS.A)
  await page.getByTestId('setup-submit').click()
  await expect(page.getByTestId('app')).toBeVisible({ timeout: 15_000 })
}

test('Solo diário: navegação, entrada, micro-passos e finanças pessoais sem controles de casal', async ({ page, errors }) => {
  void errors
  await createSolo(page)
  await expect(page.locator('[data-testid="viewer-A"]:visible, [data-testid="viewer-B"]:visible')).toHaveCount(0)
  await expect(page.locator('[data-testid="nav-nos"]:visible, [data-testid="side-nos"]:visible')).toHaveText('Espaço')
  await expect(page.locator('[data-testid="dock-sos"]:visible, [data-testid="side-quick-sos"]:visible')).toHaveText('Travei')
  await quick(page, 'task')
  const task = page.getByTestId('sheet-task')
  await expect(task.getByText('Para quem', { exact: true })).toHaveCount(0)
  await expect(task.getByText(/Só eu vejo/)).toHaveCount(0)
  await task.getByTestId('task-title').fill('Organizar documentos sem pressa')
  await task.getByRole('radio', { name: 'Caixa de Entrada', exact: true }).click()
  await task.getByTestId('task-steps-toggle').click()
  await task.getByTestId('task-step-1').fill('Abrir a pasta')
  await task.getByTestId('task-save').click()
  await page.getByTestId('today-inbox').click()
  await expect(page.getByTestId('agenda-INBOX')).toHaveAttribute('aria-checked', 'true')
  await expect(page.getByText('Organizar documentos sem pressa', { exact: true })).toBeVisible()
  await expect(page.getByRole('radiogroup', { name: 'Filtrar por pessoa' })).toHaveCount(0)
  await goTab(page, 'financas')
  await expect(page.getByTestId('solo-finance')).toBeVisible()
  await expect(page.getByTestId('fin-US')).toHaveCount(0)
  await page.getByTestId('budget-edit').click()
  await page.getByTestId('budget-amount').fill('120000')
  await page.getByTestId('budget-save').click()
  await expect(page.getByTestId('budget-progress')).toHaveAttribute('aria-valuetext', /1.200,00/)
  await noHorizontalOverflow(page)
  await goTab(page, 'rotinas')
  await expect(page.getByRole('heading', { name: /^Minhas rotinas/ })).toBeVisible()
  await expect(page.getByTestId('cycle-section')).toHaveCount(0)
})

test('conta pessoal prevista aparece no Hoje e a baixa entra no resumo pessoal', async ({ page, errors }) => {
  void errors
  await createSolo(page)
  await goTab(page, 'financas')
  await page.getByTestId('rule-add-PERSONAL').click()
  const expense = page.getByTestId('sheet-expense')
  await expect(expense.getByText('De quem é o gasto', { exact: true })).toHaveCount(0)
  await expense.getByTestId('expense-amount').fill('3500')
  await expense.getByTestId('expense-description').fill('Minha conta de hoje')
  await expense.getByTestId('expense-save').click()
  await expect(expense).toBeHidden()
  await goTab(page, 'hoje')
  const bill = page.locator('li').filter({ hasText: 'Pagar minha conta de hoje' }).first()
  await expect(bill).toContainText('sua conta')
  await bill.getByRole('button', { name: 'Paguei', exact: true }).click()
  await goTab(page, 'financas')
  await expect(page.getByTestId('solo-realized')).toContainText('35,00')
  await goSettings(page, 'casal')
  await expect(page.getByText('Só para mim', { exact: true })).toBeVisible()
})

test('estoque, compra e gasto ficam ligados com reposição e limpeza reversível', async ({ page, errors }) => {
  void errors
  await createSolo(page)
  await goTab(page, 'rotinas')
  await page.getByTestId('add-med').click()
  const med = page.getByTestId('sheet-newMed')
  await med.getByTestId('new-med-name').fill('Cuidado de teste')
  await med.getByTestId('new-med-dosage').fill('1 unidade')
  await med.getByTestId('new-med-stock').fill('3')
  await med.getByTestId('new-med-save').click()
  await page.getByTestId('stock-shop').first().click()
  await goTab(page, 'nos')
  const item = page.locator('[data-testid="shop-row"][data-title="Cuidado de teste"]')
  await expect(item).toHaveCount(1)
  await item.getByRole('checkbox').click()
  await page.getByTestId('toast').filter({ hasText: 'Comprado: Cuidado de teste' }).getByRole('button', { name: 'Repor estoque', exact: true }).click()
  await goTab(page, 'rotinas')
  await expect(page.locator('[data-testid="med-settings"][data-med="Cuidado de teste"]')).toContainText('33')
  await goTab(page, 'nos')
  await page.getByTestId('shop-expense').click()
  const expense = page.getByTestId('sheet-expense')
  await expense.getByTestId('expense-amount').fill('2590')
  await expense.getByTestId('expense-clear-shopping').click()
  await expense.getByTestId('expense-save').click()
  await expect(item).toHaveCount(0)
  await page.getByTestId('toast').last().getByRole('button', { name: 'Desfazer', exact: true }).click()
  await expect(item).toHaveCount(1)
  await goTab(page, 'financas')
  await expect(page.getByTestId('solo-realized')).toContainText('0,00')
})

test('ritual aparece uma vez por janela e dia mesmo se for ignorado', async ({ page, errors }) => {
  void errors
  await createSolo(page)
  await expect(page.getByTestId('ritual-morning')).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('app')).toBeVisible({ timeout: 15_000 })
  await expect(page.getByTestId('ritual-morning')).toHaveCount(0)
  await page.clock.fastForward(24 * 60 * 60_000)
  await expect(page.getByTestId('ritual-morning')).toBeVisible()
  await page.getByTestId('ritual-dismiss').click()
  await expect(page.getByTestId('ritual-morning')).toHaveCount(0)
})
