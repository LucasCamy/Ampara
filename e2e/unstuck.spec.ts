import { at, expect, goTab, noHorizontalOverflow, PASSWORDS, quick, skipTour, test } from './fixtures'

test('Travei escolhe micro-passo, inicia cinco minutos e permite estender e concluir', async ({ page, errors }) => {
  void errors
  await at(page, '10:00')
  await skipTour(page)
  await page.goto('/')
  await page.getByTestId('setup-mode-solo').click()
  await page.getByTestId('setup-name').fill('Lucas')
  await page.getByTestId('setup-password').fill(PASSWORDS.A)
  await page.getByTestId('setup-password2').fill(PASSWORDS.A)
  await page.getByTestId('setup-submit').click()
  await expect(page.getByTestId('app')).toBeVisible({ timeout: 15_000 })
  await quick(page, 'task')
  await page.getByTestId('task-title').fill('Arrumar a mesa')
  await page.getByTestId('task-save').click()
  await expect(page.getByTestId('sheet-task')).toBeHidden()
  await quick(page, 'sos')
  const flow = page.getByTestId('unstuck-flow')
  await flow.getByTestId('unstuck-reason-task').click()
  await flow.getByTestId('unstuck-task').filter({ hasText: 'Arrumar a mesa' }).click()
  await expect(flow).toHaveAttribute('data-step', '2')
  await flow.getByTestId('unstuck-choice-micro').click()
  await flow.getByTestId('unstuck-micro-input').fill('Juntar só os papéis')
  await noHorizontalOverflow(page)
  await page.getByTestId('unstuck-start').click()
  await expect(flow).toBeHidden()
  const focus = page.getByTestId('focus-card')
  await expect(focus).toHaveAttribute('data-state', 'running')
  await expect(focus).toContainText('Juntar só os papéis')
  await expect(focus.getByTestId('focus-left')).toContainText('5 min')
  await page.clock.fastForward(5 * 60_000 + 1000)
  await expect(focus).toHaveAttribute('data-state', 'finished')
  await focus.getByRole('button', { name: '+10 min', exact: true }).click()
  await expect(focus).toHaveAttribute('data-state', 'running')
  await page.clock.fastForward(10 * 60_000 + 1000)
  await expect(focus).toHaveAttribute('data-state', 'finished')
  await expect(focus.getByRole('button', { name: 'Fazer pausa', exact: true })).toBeVisible()
  await focus.getByTestId('focus-finish').click()
  await expect(focus).toBeHidden()
  await goTab(page, 'agenda')
  await expect(page.getByRole('checkbox', { name: 'Reabrir: Arrumar a mesa', exact: true })).toHaveAttribute('aria-checked', 'true')
})
