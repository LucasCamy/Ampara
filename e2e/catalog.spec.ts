import { at, expect, goTab, noHorizontalOverflow, open, shot, test } from './fixtures'

/** Cadastros novos: remédio, rotina da casa e compromisso (validação inline, salvar no rodapé, Desfazer) */
test('Cadastrar remédio, rotina e compromisso pelas gavetas', async ({ page, errors }, info) => {
  void errors
  await at(page, '07:30')
  await open(page)

  // ---- Remédio: erro inline primeiro, depois salva
  await goTab(page, 'rotinas')
  await page.getByTestId('add-med').click()
  const med = page.getByTestId('sheet-newMed')
  await med.getByTestId('new-med-save').click()
  await expect(med.getByRole('alert').first()).toContainText('nome do remédio')
  await expect(med.getByTestId('new-med-name')).toHaveAttribute('aria-invalid', 'true')
  await med.getByTestId('new-med-name').fill('Ritalina 10mg')
  await med.getByTestId('new-med-dosage').fill('1 comprimido')
  await med.getByTestId('new-med-time-0').fill('09:15')
  await med.getByTestId('new-med-stock').fill('20')
  await med.getByTestId('new-med-share').click()
  await noHorizontalOverflow(page)
  await shot(page, '30-novo-remedio', info.project.name)
  await med.getByTestId('new-med-save').click()
  await expect(med).toBeHidden()
  await expect(page.getByText('Remédio salvo · Ritalina 10mg às 09:15 · com rede de apoio')).toBeVisible()
  await expect(page.locator('[data-testid="dose-card"][data-med="Ritalina 10mg"]')).toContainText('09:15')

  // ---- Rotina em dias escolhidos, com responsável e estoque
  await page.getByTestId('add-routine').click()
  const routine = page.getByTestId('sheet-routine')
  await routine.getByTestId('routine-title').fill('Regar as plantas')
  await routine.getByTestId('routine-time-0').fill('18:00')
  await routine.getByRole('radio', { name: 'Escolher dias' }).click()
  await routine.getByTestId('routine-save').click()
  await expect(routine.getByRole('alert')).toContainText('pelo menos um dia')
  await routine.getByRole('button', { name: 'terça' }).click()
  await routine.getByRole('button', { name: 'sexta' }).click()
  await routine.getByRole('radio', { name: 'Meu' }).click()
  await routine.getByTestId('routine-stock').fill('3')
  await routine.getByTestId('routine-unit').fill('sachês')
  await routine.getByTestId('routine-save').click()
  await expect(routine).toBeHidden()
  const card = page.getByTestId('routine-card').filter({ hasText: 'Regar as plantas' })
  await expect(card).toContainText('Ter, Sex')
  await expect(card).toContainText('Responsável: você')
  await expect(card).toContainText('3 sachês')

  // Desfazer remove na hora
  await page.getByRole('button', { name: 'Desfazer' }).last().click()
  await expect(page.getByTestId('routine-card').filter({ hasText: 'Regar as plantas' })).toHaveCount(0)

  // ---- Compromisso: término antes do início é recusado
  await goTab(page, 'agenda')
  await page.getByTestId('agenda-new-event').click()
  const ev = page.getByTestId('sheet-event')
  await ev.getByTestId('event-title').fill('Consulta médica')
  await ev.getByTestId('event-start').fill('16:00')
  await ev.getByTestId('event-end').fill('15:00')
  await ev.getByTestId('event-save').click()
  await expect(ev.getByRole('alert')).toContainText('depois do início')
  await ev.getByTestId('event-end').fill('17:00')
  await ev.getByRole('radio', { name: /Saúde/ }).click()
  await ev.getByTestId('event-save').click()
  await expect(ev).toBeHidden()
  await expect(page.getByText('Consulta médica')).toBeVisible()
  await expect(page.getByText('Saúde / remédio').first()).toBeVisible()
  await noHorizontalOverflow(page)
})

test('Editar e excluir remédio, rotina e compromisso (com Desfazer)', async ({ page, errors }, info) => {
  void errors
  await at(page, '07:30')
  await open(page)

  // ---- Remédio do exemplo: segunda dose às 20:00 e dose nova
  await goTab(page, 'rotinas')
  const settings = page.locator('[data-testid="med-settings"][data-med="Vitamina D 2000UI"]')
  await settings.getByTestId('med-edit').click()
  const med = page.getByTestId('sheet-newMed')
  await expect(med).toContainText('Editar remédio')
  await expect(med.getByTestId('new-med-name')).toHaveValue('Vitamina D 2000UI')
  await med.getByTestId('new-med-time-add').click()
  await med.getByTestId('new-med-time-1').fill('13:00')
  await med.getByTestId('new-med-save').click()
  await expect(med.getByRole('alert')).toContainText('dois horários iguais')
  await med.getByTestId('new-med-time-1').fill('20:00')
  await med.getByTestId('new-med-dosage').fill('2 gotas')
  await noHorizontalOverflow(page)
  await shot(page, '31-editar-remedio', info.project.name)
  await expect(med.getByTestId('new-med-save')).toHaveText('Salvar alterações')
  await med.getByTestId('new-med-save').click()
  await expect(med).toBeHidden()
  await expect(settings).toContainText('2 gotas · 13:00, 20:00')
  await expect(page.locator('[data-testid="dose-card"][data-med="Vitamina D 2000UI"]')).toHaveCount(2)

  // excluir e desfazer
  await settings.getByTestId('med-edit').click()
  await med.getByTestId('new-med-delete').click()
  await expect(med).toBeHidden()
  await expect(settings).toHaveCount(0)
  await page.getByRole('button', { name: 'Desfazer' }).last().click()
  await expect(settings).toContainText('2 gotas')

  // ---- Rotina com dias escolhidos abre já em "Escolher dias"
  const lixo = page.getByTestId('routine-card').filter({ hasText: 'Tirar o lixo' })
  await lixo.getByTestId('routine-edit').click()
  const routine = page.getByTestId('sheet-routine')
  await expect(routine.getByRole('radio', { name: 'Escolher dias' })).toHaveAttribute('aria-checked', 'true')
  await expect(routine.getByRole('button', { name: 'segunda' })).toHaveAttribute('aria-pressed', 'true')
  await routine.getByRole('button', { name: 'sábado' }).click()
  await routine.getByTestId('routine-save').click()
  await expect(routine).toBeHidden()
  await expect(lixo).toContainText('Seg, Qua, Sex, Sáb')
  await lixo.getByTestId('routine-edit').click()
  await routine.getByTestId('routine-delete').click()
  await expect(page.getByTestId('routine-card').filter({ hasText: 'Tirar o lixo' })).toHaveCount(0)

  // ---- Compromisso do exemplo: muda o horário pela Agenda e depois exclui
  await goTab(page, 'agenda')
  const row = page.getByTestId('event-row').filter({ hasText: 'Jantar com a família' })
  await row.getByTestId('event-edit').click()
  const ev = page.getByTestId('sheet-event')
  await expect(ev.getByTestId('event-title')).toHaveValue('Jantar com a família')
  await ev.getByTestId('event-start').fill('20:00')
  await ev.getByTestId('event-end').fill('21:30')
  await ev.getByTestId('event-save').click()
  await expect(ev).toBeHidden()
  await expect(row).toContainText('20:00 a 21:30')
  await row.getByTestId('event-edit').click()
  await ev.getByTestId('event-delete').click()
  await expect(page.getByTestId('event-row').filter({ hasText: 'Jantar com a família' })).toHaveCount(0)
  await noHorizontalOverflow(page)
})

/** Data e hora com a cara do app: ícone Lucide, atalhos em chips e término acompanhando o início */
test('Atalhos de data e hora nas gavetas', async ({ page, errors }, info) => {
  void errors
  await at(page, '07:30') // quinta, 05/11
  await open(page)

  await goTab(page, 'agenda')
  await page.getByTestId('agenda-new-event').click()
  const ev = page.getByTestId('sheet-event')
  await ev.getByTestId('event-title').fill('Feira do bairro')

  const dates = ev.getByTestId('event-date-shortcuts')
  await expect(dates.getByRole('button')).toHaveText(['Hoje', 'Amanhã', 'Sáb 7/11'])
  await expect(dates.getByRole('button', { name: /^Hoje/ })).toHaveAttribute('aria-pressed', 'true')
  await dates.getByRole('button', { name: 'sábado, 7 de novembro' }).click()
  await expect(ev.getByTestId('event-date')).toHaveValue('2026-11-07')
  await expect(ev.getByText('sábado, 7 de novembro')).toBeVisible()

  // início leva o término junto (mantém 1 h); duração a partir do início
  await ev.getByTestId('event-start-shortcuts').getByRole('button', { name: '09:00' }).click()
  await expect(ev.getByTestId('event-end')).toHaveValue('10:00')
  await expect(ev.getByTestId('event-end-shortcuts').getByRole('button', { name: /\+1 h/ })).toHaveAttribute('aria-pressed', 'true')
  await ev.getByTestId('event-end-shortcuts').getByRole('button', { name: '+2 h, termina às 11:00' }).click()
  await expect(ev.getByTestId('event-end')).toHaveValue('11:00')
  await noHorizontalOverflow(page)
  await shot(page, '32-atalhos-data-hora', info.project.name)
  await ev.getByTestId('event-save').click()
  await expect(ev).toBeHidden()
  await expect(page.getByText('Compromisso salvo · 07/11 das 09:00 às 11:00')).toBeVisible()

  // remédio: o atalho vale para o horário tocado por último
  await goTab(page, 'rotinas')
  await page.getByTestId('add-med').click()
  const med = page.getByTestId('sheet-newMed')
  await med.getByTestId('new-med-name').fill('Ômega 3')
  await med.getByTestId('new-med-dosage').fill('1 cápsula')
  await med.getByTestId('new-med-time-shortcuts').getByRole('button', { name: '08:00' }).click()
  await med.getByTestId('new-med-time-add').click()
  await med.getByTestId('new-med-time-shortcuts').getByRole('button', { name: '20:00' }).click()
  await expect(med.getByTestId('new-med-time-0')).toHaveValue('08:00')
  await expect(med.getByTestId('new-med-time-1')).toHaveValue('20:00')
  await med.getByTestId('new-med-time-0').focus()
  await med.getByTestId('new-med-time-shortcuts').getByRole('button', { name: '12:00' }).click()
  await expect(med.getByTestId('new-med-time-0')).toHaveValue('12:00')
  await noHorizontalOverflow(page)
  await med.getByTestId('new-med-save').click()
  await expect(page.getByText(/Remédio salvo · Ômega 3 às 12:00/)).toBeVisible()
})

/** Semana no computador (>= 1024px): concluir e reabrir direto no card, com ícone, texto e traço */
test('Concluir tarefa na visão Semana do computador', async ({ page, errors }, info) => {
  void errors
  test.skip(!info.project.name.startsWith('desktop'), 'os cards compactos da Semana só aparecem em >= 1024px')
  await at(page, '09:00')
  await open(page)
  await goTab(page, 'agenda')
  await page.getByRole('radio', { name: 'Semana' }).click()
  const card = page.getByTestId('week-task').filter({ hasText: 'Comprar ração do gato' }).first()
  const toggle = card.getByTestId('week-task-toggle')
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(toggle).toHaveAccessibleName('Reabrir: Comprar ração do gato')
  await expect(card).toContainText('Feita')
  await expect(card).toHaveClass(/ledger-ok/)
  await shot(page, '33-semana-concluir', info.project.name)
  // Desfazer pelo Toast devolve como pendente
  await page.getByRole('button', { name: 'Desfazer' }).last().click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(card).not.toContainText('Feita')
})
